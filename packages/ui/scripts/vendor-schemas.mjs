// Vendors the core wire schemas into the UI package so ajv can validate every response offline.
//
//   node scripts/vendor-schemas.mjs           rewrite src/api/schemas/ and test/fixtures/schema-examples/
//   node scripts/vendor-schemas.mjs --check   exit 1 when the vendored copies differ from core
//
// Source of truth: packages/core/arp_notes/schemas (generated from the Pydantic models, K§7). The
// copies are byte-identical; src/api/schemas/index.js maps each model name (the schema's `title`)
// to its schema. `test/schemas-drift.test.js` runs the check, so CI fails when core changes and
// this script was not rerun.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = resolve(here, '..')
const CORE = resolve(pkg, '../core/arp_notes/schemas')
const SCHEMAS_OUT = join(pkg, 'src/api/schemas')
const EXAMPLES_OUT = join(pkg, 'test/fixtures/schema-examples')

const camel = (file) =>
  file.replace(/\.json$/, '').replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase())

function jsonFiles(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
}

/** The files this script owns, as {path (relative to the package), content}. */
export function expectedFiles() {
  const out = new Map()
  const entries = []
  for (const file of jsonFiles(CORE)) {
    const text = readFileSync(join(CORE, file), 'utf8')
    const name = JSON.parse(text).title
    if (!name) throw new Error(`${file}: schema has no title`)
    out.set(`src/api/schemas/${file}`, text)
    entries.push({ file, name, ident: camel(file) })
  }
  const imports = entries.map((e) => `import ${e.ident} from './${e.file}'`).join('\n')
  const map = entries.map((e) => `  ${e.name}: ${e.ident},`).join('\n')
  out.set(
    'src/api/schemas/index.js',
    `// GENERATED by scripts/vendor-schemas.mjs from packages/core/arp_notes/schemas. Do not edit.\n` +
      `${imports}\n\n` +
      `/** Model name (the schema's title) -> JSON Schema 2020-12 document. */\n` +
      `export const schemas = {\n${map}\n}\n`,
  )
  const examples = join(CORE, 'examples')
  for (const file of jsonFiles(examples)) {
    out.set(`test/fixtures/schema-examples/${file}`, readFileSync(join(examples, file), 'utf8'))
  }
  return out
}

function listDisk() {
  const found = new Set()
  for (const [dir, rel] of [
    [SCHEMAS_OUT, 'src/api/schemas'],
    [EXAMPLES_OUT, 'test/fixtures/schema-examples'],
  ]) {
    if (!existsSync(dir)) continue
    for (const f of readdirSync(dir)) found.add(`${rel}/${f}`)
  }
  return found
}

/** Returns the list of drifted paths (empty = in sync). */
export function drift() {
  const expected = expectedFiles()
  const problems = []
  for (const [path, content] of expected) {
    const abs = join(pkg, path)
    if (!existsSync(abs)) problems.push(`missing: ${path}`)
    else if (readFileSync(abs, 'utf8') !== content) problems.push(`changed: ${path}`)
  }
  for (const path of listDisk()) if (!expected.has(path)) problems.push(`stale: ${path}`)
  return problems
}

function write() {
  const expected = expectedFiles()
  for (const dir of [SCHEMAS_OUT, EXAMPLES_OUT]) mkdirSync(dir, { recursive: true })
  for (const path of listDisk()) if (!expected.has(path)) rmSync(join(pkg, path))
  for (const [path, content] of expected) writeFileSync(join(pkg, path), content)
  console.log(`vendored ${expected.size} files`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const problems = drift()
    if (problems.length) {
      console.error(`Vendored schemas drift from packages/core:\n  ${problems.join('\n  ')}`)
      console.error('Run: npm run schemas:vendor --workspace packages/ui')
      process.exit(1)
    }
    console.log('vendored schemas are in sync with core')
  } else {
    write()
  }
}
